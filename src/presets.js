function localizedExplanation(explanation, locale) {
  if (!explanation) return null;
  return explanation[locale] || explanation.en || explanation['pt-BR'] || null;
}

function publicPreset(preset, locale) {
  return {
    presetKey: preset.presetKey,
    type: preset.type,
    name: preset.name,
    mareMode: preset.mareMode,
    description: preset.description,
    explanation: localizedExplanation(preset.explanation, locale),
  };
}

